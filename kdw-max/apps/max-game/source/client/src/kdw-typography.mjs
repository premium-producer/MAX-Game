// Presentation only: preserve wording, user input, catalog IDs and explicit lines.
const NBSP='\u00a0';
// Authored semantic breaks for reference panels; fields and catalog data stay intact.
const instructionLines=new Map([
 ['Настроим тип канала – приватный или публичный','Настроим тип канала –\nприватный или публичный'],
 ['Канал создан! Начинаем делиться самым важным','Канал создан!\nНачинаем делиться самым важным']
]);
export const instructionText=value=>instructionLines.get(String(value??'').replace(/\s+/gu,' ').trim())??String(value??'');
const forward=/(?<![\p{L}\p{N}_])(?:из-за|из-под|без|для|при|над|под|про|или|во|со|ко|об|от|до|по|из|за|на|не|ни|но|да|в|с|к|у|о|и|а)[ \t]+(?=[«„“"'(\[]*[\p{L}\p{N}])/giu;
const backward=/(?<=[\p{L}\p{N}»”"')\]])[ \t]+(?=(?:бы|же|ли|б|ж|ль)(?![\p{L}\p{N}_]))/giu;
const protectedText=/((?:https?:\/\/|www\.)[^\s<>]+|[\p{L}\p{N}._%+-]+@[\p{L}\p{N}.-]+\.[\p{L}]{2,})/giu;
export function typographyText(value){
 return String(value??'').split(protectedText).map((part,i)=>i%2?part:part
  .replace(forward,s=>s.replace(/[ \t]+$/,NBSP))
  .replace(backward,NBSP)
  .replace(/[ \t]+([—–])(?=[ \t])/gu,NBSP+'$1')
  .replace(/(\d)[ \t]+(?=(?:₽|%|руб\.|кг|г|км|м|см|мм|л|мл|мин|сек)(?![\p{L}\p{N}_]))/giu,'$1'+NBSP)
 ).join('');
}
const escape=value=>value.replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const decode=value=>value.replace(/&(amp|lt|gt|quot|#39);/g,(_s,k)=>({amp:'&',lt:'<',gt:'>',quot:'"','#39':"'"}[k]));
// Only trusted markup generated by the game's renderer. Attributes/SVG paths
// are never processed; escaped user content remains escaped after formatting.
// Keep short words with an atomic branded term even across its inline boundary.
const beforeProtectedTerm=/(?<![\p{L}\p{N}_])((?:(?:из-за|из-под|без|для|при|над|под|про|или|во|со|ко|об|от|до|по|из|за|на|не|ни|но|да|в|с|к|у|о|и|а)[ \t\u00a0]+)+)(<span class="v5-copy-nowrap">)/giu;
export const typographyMarkup=markup=>String(markup)
 .replace(beforeProtectedTerm,(_s,words,span)=>span+words)
 .replace(/(^|>)([^<]+)/g,(_s,p,text)=>p+escape(typographyText(decode(text))));
